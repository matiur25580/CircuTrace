import { randomUUID } from 'node:crypto';
import cors from 'cors';
import express from 'express';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import helmet from 'helmet';
import { env } from './config/env.js';
import { errorHandler } from './middleware/error-handler.js';
import { notFoundHandler } from './middleware/not-found.js';
import { healthRouter } from './routes/health.routes.js';
import { authRouter } from './routes/auth.routes.js';
import { organizationRouter } from './routes/organization.routes.js';
import { productRouter } from './routes/product.routes.js';
import { lifecycleRouter } from './routes/lifecycle.routes.js';
import { passportRouter } from './routes/passport.routes.js';

export const app = express();
app.disable('x-powered-by');
app.set('trust proxy', 1);
app.use((request, response, next) => {
  const requestId = request.header('x-request-id')?.slice(0, 128) || randomUUID();
  request.requestId = requestId;
  response.setHeader('x-request-id', requestId);
  next();
});
app.use((request, response, next) => {
  const startedAt = process.hrtime.bigint();
  response.on('finish', () => {
    const durationMs = Number(process.hrtime.bigint() - startedAt) / 1_000_000;
    const log = { level: response.statusCode >= 500 ? 'error' : response.statusCode >= 400 ? 'warn' : 'info', requestId: request.requestId, method: request.method, path: request.path, statusCode: response.statusCode, durationMs: Math.round(durationMs * 100) / 100 };
    const output = JSON.stringify(log);
    if (response.statusCode >= 500) console.error(output);
    else if (response.statusCode >= 400) console.warn(output);
    else if (env.LOG_LEVEL !== 'silent') console.info(output);
  });
  next();
});
app.use(helmet());
app.use(cors({ origin: env.CLIENT_ORIGIN, credentials: true, methods: ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'] }));
app.use(express.json({ limit: '1mb' }));
app.use(express.urlencoded({ extended: false, limit: '1mb' }));
app.use(cookieParser());
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: 'draft-7', legacyHeaders: false }));
app.get('/', (_request, response) => response.json({ name: 'CircuTrace API', version: 'v1', docs: '/api/v1/health' }));
app.use('/api/v1/health', healthRouter);
app.use('/api/v1/auth', authRouter);
app.use('/api/v1/organizations', organizationRouter);
app.use('/api/v1/products', productRouter);
app.use('/api/v1/lifecycle', lifecycleRouter);
app.use('/api/v1/passports', passportRouter);
app.use(notFoundHandler);
app.use(errorHandler);
